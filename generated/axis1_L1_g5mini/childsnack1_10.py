from fnmatch import fnmatch
from heuristics.heuristic_base import Heuristic


def get_parts(fact):
    """
    Extract components of a PDDL fact string by removing surrounding parentheses
    and splitting on whitespace. E.g. "(at X Y)" -> ["at", "X", "Y"].
    """
    return fact[1:-1].split()


def match(fact, *pattern):
    """
    Test whether a fact (string) matches a pattern of tokens (wildcards '*' allowed).
    """
    parts = get_parts(fact)
    return all(fnmatch(part, pat) for part, pat in zip(parts, pattern))


class NewDomainDependentHeuristic(Heuristic):
    """
    Summary
    -------
    Domain-dependent heuristic for the `secret_domain` (named `biqhd61z` in the
    PDDL). The domain models producing sandwiches, placing them on trays, moving
    trays to children, and giving sandwiches to children to achieve facts of
    the form (ivo59apj childX). This heuristic estimates the number of actions
    required to reach the goal (all target children having ivo59apj).

    Assumptions
    -----------
    - The planner represents facts as strings of the form "(predicate arg1 arg2 ...)".
    - Static relations (such as child types and child->table mapping) are provided
      in `task.static` and remain valid throughout planning.
    - There exist operators in the domain that:
        * produce i9fq3vit from a sandwich (kdzjcqwj or h0xkysus),
        * produce mpvvhjpt (attach sandwich to tray) from i9fq3vit when the tray
          is at the special table `bupp7mhz` (jhzk46zy),
        * move trays between tables (whgyhnl0),
        * give sandwich on tray to a child (nfarwtet or xtn2vmez) producing ivo59apj.
    - We ignore complex resource contention (we compute a per-child optimistic
      minimal cost and sum). This makes the heuristic inadmissible but
      informative and cheap to compute.

    Heuristic Initialization
    ------------------------
    In the constructor we extract relevant static information from the task:
    - Which objects are children that require the special l2thmd6e attribute
      (those that appear in static as (n2ij1fah childX)).
    - Which children are of the other type (dr25ifx3).
    - Mapping from child -> table provided by (eyker22y child table) static facts.
    - The set of tray objects (eoraohfl) is not strictly required statically,
      but we treat y0rxzzmc facts dynamically to detect trays' locations.
    - Store the set of goal facts (task.goals).

    Step-By-Step Thinking for Computing Heuristic
    ---------------------------------------------
    For every goal child (the goals are facts like "(ivo59apj childX)") we:
    1. If the goal fact is already present in the current state, cost = 0 for that child.
    2. Otherwise estimate the minimal sequence length of actions necessary to make
       (ivo59apj childX) true, under optimistic reuse assumptions:
       - Primary ways to obtain ivo59apj(child) are the actions nfarwtet or xtn2vmez.
         Preconditions for these include:
           * mpvvhjpt ?sandw ?tray  (sandwich attached to a tray),
           * y0rxzzmc ?tray ?child_table (tray located at the child's table),
           * either n2ij1fah(child) (requires the sandwich to have l2thmd6e)
             or dr25ifx3(child) (does not need l2thmd6e).
       - mpvvhjpt is generated by jhzk46zy which requires i9fq3vit ?sandw and a tray
         located at the special table `bupp7mhz`.
       - i9fq3vit is produced by either kdzjcqwj (also produces l2thmd6e) or
         h0xkysus (does not produce l2thmd6e). Use kdzjcqwj when the child
         requires l2thmd6e (n2ij1fah children), otherwise h0xkysus is sufficient.
       - Moving a tray between tables is performed with whgyhnl0 and costs 1 action.
    3. The estimate considers existing facts to avoid unnecessary work:
       - If there already is a suitable mpvvhjpt(sandw, tray) and the sandwich
         has l2thmd6e when required, we only need to move the tray to the child's
         table (0 or 1 whgyhnl0) and then apply nfarwtet/xtn2vmez (1 action).
       - If there is a suitable i9fq3vit sandwich but no mpvvhjpt, we need to:
         (a) ensure a tray is at `bupp7mhz` (0 or 1 whgyhnl0),
         (b) call jhzk46zy (1),
         (c) move the tray to the child's table if necessary (0 or 1),
         (d) call nfarwtet/xtn2vmez (1).
       - If no appropriate i9fq3vit exists, we include the cost of making one:
         * For n2 children prefer kdzjcqwj (creates i9fq3vit and l2thmd6e) if the
           required supporting facts (bread/content attributes) exist.
         * For dr25 children prefer h0xkysus (cheaper preconditions).
    4. For infeasible sub-cases (no way to create i9fq3vit because necessary
       bread/content/sandwich facts are missing) we assign a large finite cost
       (a conservative penalty) instead of infinity, so the heuristic remains
       finite while indicating difficulty.
    5. Sum the per-child costs to produce the heuristic value.

    Implementation notes
    --------------------
    - The heuristic is intentionally optimistic about resource reuse (it treats
      each child independently). This often yields informative guidance while
      keeping computation cheap.
    - All parsing of facts strips the surrounding parentheses before splitting.
    """

    def __init__(self, task):
        # Goal facts are stored to quickly check whether a goal is satisfied.
        self.goals = set(task.goals)
        # Static facts (those that never change) are used to identify child types
        # and child -> table mappings.
        static = task.static

        # Children that require l2thmd6e (n2ij1fah) and children that are of the
        # other type (dr25ifx3) are read from static facts.
        self.n2_children = {get_parts(fact)[1] for fact in static if match(fact, "n2ij1fah", "*")}
        self.dr_children = {get_parts(fact)[1] for fact in static if match(fact, "dr25ifx3", "*")}

        # Map child -> table from eyker22y static facts.
        self.child_table = {}
        for fact in static:
            if match(fact, "eyker22y", "*", "*"):
                _, child, table = get_parts(fact)
                self.child_table[child] = table

        # Identify breads that have the e6jz04yd attribute (used by kdzjcqwj).
        self.breads_with_e6 = {get_parts(f)[1] for f in static if match(f, "e6jz04yd", "*")}
        # Identify contents that have the odd6wyd1 attribute (used by kdzjcqwj).
        self.contents_with_odd = {get_parts(f)[1] for f in static if match(f, "odd6wyd1", "*")}

        # Keep the special table constant name that appears in domain as bupp7mhz.
        # We do not assume it's always present in static, but it's constant and used
        # by jhzk46zy precondition; for matching we simply use the literal name.
        self.special_table = "bupp7mhz"

        # Store the set of goal children (extract child names from goal facts if goals are ivo59apj ...)
        self.goal_children = []
        for g in self.goals:
            parts = get_parts(g)
            if parts[0] == "ivo59apj" and len(parts) >= 2:
                self.goal_children.append(parts[1])

        # Penalty cost used when an operation seems impossible given current facts.
        self.impossible_penalty = 1000

    def __call__(self, node):
        """
        Compute heuristic estimate: sum over goal children of an optimistic minimal
        number of actions needed to make (ivo59apj child) true, given the current state.
        """
        state = node.state

        # Quick check: if goal already satisfied, heuristic is 0.
        if self.goals <= state:
            return 0

        # Helper predicates to query the current state.
        def fact_exists(pred, *args):
            """Return True if a fact matching pred and args exists in the current state."""
            for f in state:
                if match(f, pred, *args):
                    return True
            return False

        # Build indices of facts for quick queries:
        # - which trays are at which tables (y0rxzzmc tray table)
        trays_at_table = {}
        for f in state:
            if match(f, "y0rxzzmc", "*", "*"):
                _, tray, table = get_parts(f)
                trays_at_table.setdefault(tray, set()).add(table)

        # - which sandwiches (uguffgcw) have i9fq3vit
        i9_sandwiches = {get_parts(f)[1] for f in state if match(f, "i9fq3vit", "*")}

        # - which sandwiches have l2thmd6e
        l2_sandwiches = {get_parts(f)[1] for f in state if match(f, "l2thmd6e", "*")}

        # - existing mpvvhjpt relations: sandwich -> tray
        mp_on_tray = {}
        for f in state:
            if match(f, "mpvvhjpt", "*", "*"):
                _, sandw, tray = get_parts(f)
                mp_on_tray.setdefault(sandw, set()).add(tray)

        # - which trays currently are at the special table bupp7mhz
        trays_at_special = {tray for tray, tables in trays_at_table.items() if self.special_table in tables}

        # - which trays are at a given table: we will query using trays_at_table
        # - presence of breads and contents that are usable:
        breads = {get_parts(f)[1] for f in state if match(f, "go9lczo2", "*")}
        contents = {get_parts(f)[1] for f in state if match(f, "fqungbps", "*")}
        sandwiches_available_for_h0 = {get_parts(f)[1] for f in state if match(f, "zogo0zhl", "*")}
        # For kdzjcqwj we need a sandwich (zogo0zhl), a bread that has both go9lczo2 and e6jz04yd,
        # and a content that has both fqungbps and odd6wyd1.
        breads_for_kdz = {b for b in breads if b in self.breads_with_e6}
        contents_for_kdz = {c for c in contents if c in self.contents_with_odd}
        sandwiches_available_for_kdz = sandwiches_available_for_h0  # same sandwiches but stronger bread/content requirements

        total_cost = 0

        # For each goal child, estimate minimal cost independently.
        for child in self.goal_children:
            goal_fact = f"(ivo59apj {child})"
            if goal_fact in state:
                continue  # already satisfied

            # Determine child type and required sandwich attribute.
            needs_l2 = child in self.n2_children  # if True need l2thmd6e on sandwich
            child_table = self.child_table.get(child, None)

            # 1) Check if there is already an mpvvhjpt(sandw, tray) that is suitable.
            best_cost_for_child = None

            for sandw, trays in mp_on_tray.items():
                if needs_l2 and sandw not in l2_sandwiches:
                    continue  # this mpvvhjpt's sandwich lacks required l2thmd6e

                # For any tray where the mpvvhjpt sits, compute cost to serve child:
                for tray in trays:
                    # If tray already at child's table -> only need the final serve action.
                    if child_table is not None and child_table in trays_at_table.get(tray, set()):
                        cost = 1  # nfarwtet or xtn2vmez
                    else:
                        # Need one move to move tray to child's table and final serve.
                        cost = 1 + 1
                    if best_cost_for_child is None or cost < best_cost_for_child:
                        best_cost_for_child = cost

            if best_cost_for_child is not None:
                total_cost += best_cost_for_child
                continue  # move to next child

            # 2) No existing suitable mpvvhjpt. Check if there is an appropriate i9fq3vit sandwich
            #    (and l2thmd6e if required). If so, we must create mpvvhjpt using a tray at special table.
            suitable_i9_candidates = {s for s in i9_sandwiches if (not needs_l2 or s in l2_sandwiches)}

            if suitable_i9_candidates:
                # We can create mpvvhjpt by jhzk46zy (1 action). But we may first need to
                # move a tray to the special table (if none present). Then after mpvvhjpt,
                # we might need to move tray to child's table and finally apply nfarwtet/xtn2vmez.
                cost = 0
                if not trays_at_special:
                    # Move some tray to special table (whgyhnl0)
                    cost += 1
                    # After we move a tray to special table, that tray is at special table.
                    # We don't model which specific tray; this is optimistic.
                # Create mpvvhjpt
                cost += 1  # jhzk46zy
                # If child's table is not the special table, we need to move the tray to child's table.
                if child_table is None:
                    # If we don't know child's table (missing static info), add an extra move
                    # conservatively.
                    cost += 1
                elif child_table != self.special_table:
                    cost += 1  # move tray from special table to child's table
                # Final serve
                cost += 1  # nfarwtet/xtn2vmez
                total_cost += cost
                continue

            # 3) No i9fq3vit suitable exists. We need to create one.
            #    For n2 children we prefer kdzjcqwj (creates i9fq3vit + l2thmd6e),
            #    for dr25 children we prefer h0xkysus (creates i9fq3vit only).
            # Check whether the necessary preconditions to apply kdzjcqwj/h0xkysus exist.
            # Preconditions summary:
            #   h0xkysus: exists sandw with zogo0zhl, exists bread with go9lczo2, exists content with fqungbps.
            #   kdzjcqwj: same plus bread must have e6jz04yd and content must have odd6wyd1.
            cost_make = None

            # First, if child needs l2thmd6e, prefer kdzjcqwj if applicable.
            if needs_l2:
                if sandwiches_available_for_kdz and breads_for_kdz and contents_for_kdz:
                    # One kdzjcqwj makes i9fq3vit and l2thmd6e in a single action.
                    cost_make = 1
                else:
                    # If kdzjcqwj not applicable but h0xkysus is, we technically cannot produce
                    # the l2thmd6e attribute and thus cannot serve this child using the normal
                    # nfarwtet operator. Mark as very costly (but finite).
                    if sandwiches_available_for_h0 and breads and contents:
                        cost_make = self.impossible_penalty  # indicates this child needs unavailable special prep
                    else:
                        cost_make = self.impossible_penalty
            else:
                # dr25 child: h0xkysus is sufficient
                if sandwiches_available_for_h0 and breads and contents:
                    cost_make = 1  # apply h0xkysus to create i9fq3vit
                else:
                    cost_make = self.impossible_penalty

            # After making i9fq3vit (or paying the penalty), we still need to create mpvvhjpt,
            # possibly move tray(s), and finally apply nfarwtet/xtn2vmez.
            if cost_make >= self.impossible_penalty:
                # If impossible or extremely costly to make an appropriate sandwich, just
                # add the penalty and continue.
                total_cost += cost_make
                continue

            # Otherwise, compute the remaining costs as in case (2):
            cost = cost_make
            if not trays_at_special:
                cost += 1  # move tray to special
            cost += 1  # jhzk46zy to make mpvvhjpt
            if child_table is None or child_table != self.special_table:
                cost += 1  # move tray to child's table (or unknown table)
            cost += 1  # final nfarwtet/xtn2vmez
            total_cost += cost

        # Return a finite integer heuristic estimate.
        return int(total_cost)